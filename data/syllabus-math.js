/* tag → 正名。alias 里的叫法归一到 tag；没见过的原样返回。 */
window.SYLLABUS_MATH.canon = (function () {
  var map = {};
  window.SYLLABUS_MATH.units.forEach(function (u) {
    u.points.forEach(function (p) {
      map[p.tag] = p.tag;
      (p.alias || []).forEach(function (a) { map[a] = p.tag; });
    });
  });
  return function (tag) { return map[tag] || tag; };
})();
